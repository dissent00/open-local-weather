def test_vectors_aqi_staleness():
    for case in load("aqi_staleness.json")["cases"]:
        i = case["input"]
        reading = GroundAQIReading.model_validate(i["reading"])
        now = datetime.fromisoformat(i["now"])
        got = {"hours_old": hours_old(reading, now), "is_stale": is_stale(reading, now)}
        assert got["is_stale"] == case["expected"]["is_stale"], f"vector case failed: {case['name']}"
        if case["expected"]["hours_old"] is None:
            assert got["hours_old"] is None, f"vector case failed: {case['name']}"
        else:
            assert got["hours_old"] == pytest.approx(case["expected"]["hours_old"]), f"vector case failed: {case['name']}"


def test_vectors_aqi_summary():
    for case in load("aqi_summary.json")["cases"]:
        i = case["input"]
        readings = [GroundAQIReading.model_validate(r) for r in i["readings"]]
        check(case, summarize_ground_aqi(readings, datetime.fromisoformat(i["now"])))


def test_vectors_bucket_hourly_by_date():
    for case in load("bucket_hourly_by_date.json")["cases"]:
        i = case["input"]
        result = bucket_hourly_by_date(i["hourly_json"], i["threshold"])
        got = {d.isoformat(): as_json(v) for d, v in result.items()}
        assert got == case["expected"], f"vector case failed: {case['name']}"


def test_vectors_llm_schemas():
    """Guards the structured-output contract sent to real provider APIs."""
    for case in load("llm_schema_gemini.json")["cases"]:
        assert to_gemini_schema(GeminiForecastResponse) == case["expected"]
    for case in load("llm_schema_strict.json")["cases"]:
        assert to_strict_json_schema(GeminiForecastResponse) == case["expected"]


def test_vectors_system_prompt():
    """The instruction set behind every forecast — pinned verbatim so a port
    cannot quietly reason from different instructions."""
    for case in load("llm_system_prompt.json")["cases"]:
        i = case["input"]
        loc = i["location"]
        sec = loc["secondary_point"]
        location = LocationConfig(
            region_name=loc["region_name"],
            primary_place_name=loc["primary_place_name"],
            timezone="UTC",
            primary_point=Point(lat=0.0, lon=0.0),
            secondary_point=SecondaryPoint(
                enabled=sec["enabled"], name=sec["name"], section_label=sec["section_label"]
            ),
        )
        got = build_system_prompt(
            location,
            historical_lookback_days=i["historical_lookback_days"],
            rolling_window_short=i["rolling_window_short"],
            rolling_window_long=i["rolling_window_long"],
            is_refresh=i["is_refresh"],
        )
        assert got == case["expected"], f"vector case failed: {case['name']}"


