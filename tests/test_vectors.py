"""Asserts this implementation satisfies its own exported cross-language
test vectors (spec/vectors/, generated by spec/export_vectors.py).

Why this test exists, given the same behaviour is already covered by the
hand-computed unit tests: the vectors are the contract a port in another
language is held to (see docs-internal/APP_ARCHITECTURE.md). If the Python
implementation changes and the vectors aren't regenerated, the contract
silently describes something nobody implements any more — and a Dart port
passing "the vectors" would be agreeing with a version of Python that no
longer exists. This test makes that rot impossible: change the behaviour
without regenerating, and it goes red here first.

The layering is deliberate:
  - test_scoring/test_extract/test_aqi/test_dates assert Python is RIGHT
    (hand-computed expectations)
  - this file asserts the exported vectors still MATCH Python
  - a port asserts it matches the same vectors
"""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import date, datetime
from pathlib import Path

import pytest

from openlocalweather.aqi import hours_old, is_stale, summarize_ground_aqi
from openlocalweather.dates import add_days, prediction_row_date_for_target
from openlocalweather.extract import (
    extract_day0_predictions_from_hourly,
    extract_day_n_predictions_from_daily,
)
from openlocalweather.fetch.open_meteo import bucket_hourly_by_date, get_onset_hour
