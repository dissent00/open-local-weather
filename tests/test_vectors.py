def test_every_vector_file_is_exercised():
    """A vector file with no test is a contract nobody checks. Adding one
    without wiring it up here should fail loudly rather than pass quietly."""
    covered = {
        "dates.json",
        "dates_add_days.json",
        "scoring_score_prediction.json",
        "scoring_mean.json",
        "scoring_rain_pct_trend.json",
        "extract_day0.json",
        "extract_day_n.json",
        "extract_onset_hour.json",
        "aqi_staleness.json",
        "aqi_summary.json",
        "bucket_hourly_by_date.json",
        "llm_schema_gemini.json",
        "llm_schema_strict.json",
        "llm_system_prompt.json",
    }
    on_disk = {p.name for p in VECTORS_DIR.glob("*.json")}
    assert on_disk == covered, (
        f"vector files not exercised by a test: {sorted(on_disk - covered)}; "
        f"tests referencing missing files: {sorted(covered - on_disk)}"
    )


def test_vector_files_declare_a_known_format_version():
    for path in VECTORS_DIR.glob("*.json"):
        data = json.loads(path.read_text())
        assert data.get("vector_format_version") == 1, f"{path.name} has an unexpected format version"
        assert data.get("function"), f"{path.name} is missing its function name"
        assert data.get("cases"), f"{path.name} has no cases"
