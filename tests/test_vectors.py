def test_vectors_prediction_row_date_for_target():
    data = load("dates.json")
    assert data["cases"], "vector file is empty"
    for case in data["cases"]:
        i = case["input"]
        check(case, prediction_row_date_for_target(date.fromisoformat(i["target_date"]), i["lead_time_days"]))


def test_vectors_add_days():
    for case in load("dates_add_days.json")["cases"]:
        i = case["input"]
        check(case, add_days(date.fromisoformat(i["date"]), i["days"]))


